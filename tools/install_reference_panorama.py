"""Rebuild ECHO-7 chapter scenic plates/panoramas from supplied 1280x720 extended art.

Only panoramas for Chapters 1,2,3,4,6,8 use the faithfully extended
source concept illustrations. Chapters 5 & 7 instead use the clean authored
scenic paintings generated by tools/build_scenic_backdrops.py because their
original reference scenes contain a fictitious water basin or outdoor ledges.

To rebuild: python tools/build_scenic_backdrops.py && python tools/install_reference_panorama.py
"""
from __future__ import annotations
from pathlib import Path
from PIL import Image

ROOT=Path(__file__).resolve().parents[1]
REF=ROOT/'data/art/backgrounds/reference_extended'
OUT=ROOT/'data/art/backgrounds/scenic'
PANO=(1920,960)


def reconstruct(ch: int):
    with Image.open(REF/f'Chapter_{ch:02d}.png') as source:
        src=source.convert('RGB')
        if src.size!=(1280,720):
            raise ValueError(f'Chapter {ch} must be 1280x720, got {src.size}')
        # Pixel-perfect original scene remains available for menu previews.
        src.save(OUT/f'chapter_{ch:02d}_scenic.png', optimize=True)
        # Preserve aspect ratio. The original scene is 16:9; the panoramic
        # buffer is 2:1, so take a centered vertical crop after uniform scale.
        scaled=src.resize((1920,1080), Image.Resampling.LANCZOS)
        box=(0,(1080-PANO[1])//2,PANO[0],(1080+PANO[1])//2)
        scaled.crop(box).save(OUT/f'chapter_{ch:02d}_pano.png',optimize=True)


def main():
    for ch in (1,2,3,4,6,8):
        reconstruct(ch)
        print(f'Chapter {ch}: extended source -> cached scenic and panoramic assets')

if __name__=='__main__':
    main()
